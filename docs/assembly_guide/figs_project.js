    calHand(v);
    ST.forEach(function (st) { bracket(v, st.x); });
    bracket(v, PN.x, { pen: true });
    rods(v, -1);
    penPulley(v, cy);
    carriageRear(v, cy);
    carriageBearings(v, cy);
